#!/usr/bin/env python3
"""Validate the analysis pipeline on simulated data at n = 30, 60 and 120.

For each size: simulate an export, run the full pipeline, check that every
table and figure exists and that every table and figure is watermarked. Then
write analysis/output/validation.json and generate docs/RESULTS-SKELETON.md
from the n = 60 run.

Usage: python3 analysis/validate.py
"""
from __future__ import annotations

import importlib.util
import json
import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
import simulate  # noqa: E402

_spec = importlib.util.spec_from_file_location("dlv_analysis", HERE / "analysis.py")
A = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(A)

SIZES = (30, 60, 120)
EXPECTED_TABLES = [f"T{k:02d}" for k in range(1, 18)]
EXPECTED_FIGURES = [f"F{k}" for k in range(1, 7)]


def main() -> None:
    summary = []
    for n in SIZES:
        data, out = HERE / "sim" / f"n{n}", HERE / "output" / f"sim_n{n}"
        shutil.rmtree(data, ignore_errors=True)
        shutil.rmtree(out, ignore_errors=True)
        data.mkdir(parents=True)
        for name, df in simulate.simulate(n, seed=n).items():
            df.to_csv(data / f"{name}.csv", index=False)
        (data / "SIMULATED").write_text("Synthetic data generated by analysis/simulate.py. Not real participants.\n")
        res = A.run(data, out)
        missing = [t for t in EXPECTED_TABLES for ext in ("csv", "tex") if not (out / "tables" / f"{t}.{ext}").exists()]
        missing += [f for f in EXPECTED_FIGURES for ext in ("pdf", "svg") if not (out / "figures" / f"{f}.{ext}").exists()]
        unmarked = [p.name for p in (out / "tables").glob("*.tex") if A.WATERMARK not in p.read_text()]
        report = (out / "report.md").read_text()
        captions = [m.group(0) for m in re.finditer(r"^\*\*(?:Table|Figure) \d+\.\*\* .*$", report, flags=re.M)]
        uncaptioned = [c for c in captions if A.WATERMARK not in c]
        ok = not missing and not unmarked and not uncaptioned
        summary.append({
            "n_target": n, "n_analysed": res["design"]["n_analysed"], "tables": len(EXPECTED_TABLES), "figures": len(EXPECTED_FIGURES),
            "missing": missing, "unwatermarked": unmarked + uncaptioned, "ok": ok, "primary": res["assumptions"]["primary"],
            "ancova": res["ancova"]["apa"], "kruskal": res["kruskal"]["apa"],
        })
        print(f"n={n}: analysed {res['design']['n_analysed']}, {'OK' if ok else 'FAILED'} — {res['ancova']['apa']}")
        if not ok:
            raise SystemExit(f"validation failed at n={n}: missing={missing} unwatermarked={unmarked + uncaptioned}")
    (HERE / "output" / "validation.json").write_text(json.dumps(summary, indent=2) + "\n")
    write_skeleton(summary)


def write_skeleton(summary: list[dict]) -> None:
    out = HERE / "output" / "sim_n60"
    res = json.loads((out / "results.json").read_text())
    report = (out / "report.md").read_text().split("\n", 3)[3]
    report = re.sub(r"\(`figures/(F\d)\.pdf`, `figures/F\d\.svg`\)", r"(`analysis/output/sim_n60/figures/\1.pdf`)", report)
    a, k = res["ancova"], res["kruskal"]
    rows = "\n".join(f"| {s['n_target']} | {s['n_analysed']} | {s['tables']} | {s['figures']} | {s['primary']} | {s['ancova']} |" for s in summary)
    text = f"""# Results — Skeleton

> **ILLUSTRATIVE — simulated data, pipeline validation only.**
> Every number in this document comes from synthetic participants generated by `analysis/simulate.py`. It shows the structure, test names and statistic formatting the results section will use, and proves the pipeline produces every table and figure. It is **not** a finding. Regenerate with `python3 analysis/validate.py`; on real data run `python3 analysis/analysis.py <export_dir> <output_dir>`.

## How this document maps to the paper

**Scales.** Every pre/post comparison — descriptives, the ANCOVA, paired tests, raw and normalised gains, gains by cluster and Bloom level, and Cronbach's α — uses the **matched 20-item scale**: the core items administered identically in both tests. The 4 transfer items are a separate, post-test-only outcome and never enter a pre/post comparison; never report a 20-item pre-test against a 24-item post-test.

The results section reports, in order: participant flow (Figure 1) and characteristics with baseline equivalence (Table 1); pre/post descriptives (Table 2, Figure 3); assumption checks that select the primary test (Table 3); the primary test — ANCOVA (Tables 4–6, Figure 2) or, if assumptions fail, Kruskal–Wallis with Dunn's tests (Table 7), the other reported as a sensitivity analysis; within-condition gains (Table 8); gains by concept cluster and by Bloom level (Tables 9–10, Figures 5–6; per-concept results only as the exploratory appendix Table 17); usability and workload (Tables 11–12); engagement (Tables 13–14, Figure 4); reliability (Table 15); and power (Table 16).

## Example of the primary result sentence

*ILLUSTRATIVE — simulated data, pipeline validation only.* Controlling for pre-test score, post-test scores differed by condition, {a['apa']}. (Non-parametric sensitivity analysis on gain scores: {k['apa']}.)

## Pipeline validation summary

| Target n | Analysed n | Tables | Figures | Primary analysis selected | ANCOVA |
|---|---|---|---|---|---|
{rows}

All tables and figures were produced without error at every size, and every table and figure caption carries the watermark.

## Tables and figures (from the n = 60 simulated run)

{report}
"""
    (ROOT / "docs" / "RESULTS-SKELETON.md").write_text(text)
    print("wrote docs/RESULTS-SKELETON.md")


if __name__ == "__main__":
    main()
