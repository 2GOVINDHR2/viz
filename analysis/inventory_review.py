#!/usr/bin/env python3
"""Writes analysis/output/concept-inventory-review.md: the administered concept
inventory as reviewers should see it — options shuffled (the JSON stores the
correct option first for every item, which would make distractors look more
plausible than they are), no answer marked inline, and an answer key with each
item's concept, cluster, Bloom level and distractor rationale at the end.

The shuffle uses a fixed seed so the review copy is reproducible.

Usage: python3 analysis/inventory_review.py
"""
from __future__ import annotations

import json
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INV = json.loads((ROOT / "src/study/config/concept-inventory.json").read_text())
OUT = ROOT / "analysis/output/concept-inventory-review.md"
SEED = 20261019
LETTERS = "ABCD"


def main() -> None:
    rng = random.Random(SEED)
    core = [i for i in INV["items"] if not i.get("retired")]
    transfer = [i for i in INV["transfer_items"] if not i.get("retired")]
    retired = [i for i in INV["items"] + INV["transfer_items"] if i.get("retired")]
    lines = [
        "# Concept inventory — review copy",
        "",
        f"Inventory version {INV['version']}. Generated by `analysis/inventory_review.py` (seed {SEED}) from "
        "`src/study/config/concept-inventory.json`; do not edit by hand.",
        "",
        "Options are shown in a shuffled order and the correct answer is **not** marked; the answer key is at the end. "
        "Participants see a different random item and option order each (Study Mode).",
        "",
    ]
    key = []
    for title, items in (("Part 1 — core items (pre- and post-test)", core), ("Part 2 — transfer items (post-test only)", transfer)):
        lines += [f"## {title}", ""]
        for item in items:
            order = list(range(4))
            rng.shuffle(order)
            lines.append(f"**{item['id']}.** {item['stem']}")
            lines.append("")
            for pos, canon in enumerate(order):
                lines.append(f"- {LETTERS[pos]}. {item['options'][canon]['text']}")
            lines.append("")
            correct = LETTERS[order.index(item["answer"])]
            distractors = "; ".join(
                f"{LETTERS[order.index(c)]}: {item['options'][c].get('misconception', '')}" for c in order if c != item["answer"]
            )
            key.append(f"| {item['id']} | **{correct}** | {item['concept']} | {item['cluster']} | {item['bloom']} | {item['rationale']} | {distractors} |")
    lines += [
        "## Answer key",
        "",
        "| Item | Answer | Concept | Cluster | Bloom | Rationale | Distractors (misconception targeted) |",
        "|---|---|---|---|---|---|---|",
        *key,
        "",
        "## Retired items (not administered, not scored)",
        "",
        *[f"- **{i['id']}** ({i['concept']}): {i['retired_reason']}" for i in retired],
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(core)} core + {len(transfer)} transfer items")


if __name__ == "__main__":
    main()
