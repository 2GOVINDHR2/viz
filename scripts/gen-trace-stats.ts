/**
 * Writes docs/TRACE-STATISTICS.md: how each runnable experiment decomposes
 * into individually inspectable instructions, and how trace size and
 * generation time scale with network size, batch size and epochs.
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { resolveDataset } from '../src/core/engine/host';
import * as D from '../src/core/engine/datasets';
import type { TrainConfig } from '../src/core/engine/session';
import { GRANULARITIES, TraceStore, explainedKindsCount, traceStatistics } from './trace-stats-helpers';
import { EXPERIMENTS } from '../src/experiments/registry';
import { fmtBytes, mdTable } from './docs-util';

const sections: string[] = [];
const headline: string[] = [];
for (const exp of EXPERIMENTS) {
  const { store, generationMs } = TraceStore.generate(exp.config, resolveDataset(exp.dataset));
  const all = store.range(0, store.length);
  const s = traceStatistics(all);
  const e0 = store.header.epochStarts;
  const epochOne = traceStatistics(store.range(e0[0], e0[1]));
  headline.push(
    `One epoch of the **“${exp.title}”** experiment (${store.header.dataset.n} examples, batch size ${exp.config.batchSize}) decomposes into **${epochOne.instructions.toLocaleString('en')} individually inspectable, individually explained operations** across six levels of granularity; the full ${exp.config.epochs}-epoch run has ${s.instructions.toLocaleString('en')}.`,
  );
  const kinds = Object.entries(s.byKind).sort((a, b) => b[1] - a[1]);
  sections.push(`### ${exp.title}

| Measure | Value |
|---|---|
| Instructions (full run, ${exp.config.epochs} epochs) | ${s.instructions.toLocaleString('en')} |
| Instructions in one epoch | ${epochOne.instructions.toLocaleString('en')} |
| Distinct instruction kinds used | ${kinds.length} (of ${explainedKindsCount()} registered, all explained) |
| Nesting depth (epoch → batch → sample → phase → layer → operation) | ${s.nestingDepth} |
| Granularity levels | ${s.granularityLevels} |
| Stored values | ${s.values.toLocaleString('en')} |
| Trace size in memory (full) | ${fmtBytes(s.bytes)} |
| Generation time (Node, one thread) | ${generationMs.toFixed(0)} ms |

Units per granularity (number of steps to traverse the whole run):

${mdTable([...GRANULARITIES], [GRANULARITIES.map((g) => s.unitsPerGranularity[g].toLocaleString('en'))])}

Distribution by kind:

${mdTable(
  ['Kind', 'Count', 'Share'],
  kinds.map(([k, n]) => [`\`${k}\``, n.toLocaleString('en'), `${((100 * n) / s.instructions).toFixed(1)}%`]),
)}
`);
}

const scale = (label: string, configs: [string, TrainConfig, ReturnType<typeof D.circles>][]): string =>
  `### ${label}\n\n${mdTable(
    ['Setting', 'Instructions', 'Per epoch', 'Trace size', 'Generation (ms)'],
    configs.map(([name, c, d]) => {
      const { store, generationMs } = TraceStore.generate(c, d);
      const st = store.stats();
      return [
        name,
        store.length.toLocaleString('en'),
        Math.round((store.length - store.header.epochStarts[0]) / c.epochs).toLocaleString('en'),
        fmtBytes(st.fullBytes),
        generationMs.toFixed(0),
      ];
    }),
  )}\n`;
const base = (hidden: number, batch: number, epochs: number, depth = 1): TrainConfig => ({
  seed: 1,
  epochs,
  batchSize: batch,
  shuffle: true,
  loss: 'bce',
  optimizer: { type: 'sgd', lr: 0.5 },
  model: {
    inputShape: [2],
    layers: [
      ...Array.from({ length: depth }, () => ({
        type: 'dense' as const,
        units: hidden,
        activation: 'tanh' as const,
      })),
      { type: 'dense', units: 1, activation: 'sigmoid' },
    ],
  },
});
const data = D.circles(32, 1);
const scaling = [
  scale(
    'Network width (2-H-1, 32 examples, batch 8, 5 epochs)',
    [2, 4, 8, 16, 32, 64].map((h) => [`H = ${h}`, base(h, 8, 5), data]),
  ),
  scale(
    'Network depth (2-8-…-8-1, 32 examples, batch 8, 5 epochs)',
    [1, 2, 4, 8].map((k) => [`${k} hidden layer${k > 1 ? 's' : ''}`, base(8, 8, 5, k), data]),
  ),
  scale(
    'Batch size (2-8-1, 32 examples, 5 epochs)',
    [1, 2, 4, 8, 16, 32].map((b) => [`B = ${b}`, base(8, b, 5), data]),
  ),
  scale(
    'Epochs (2-8-1, 32 examples, batch 8)',
    [1, 5, 10, 50, 100].map((e) => [`${e} epoch${e > 1 ? 's' : ''}`, base(8, 8, e), data]),
  ),
];

const doc = `# Trace Statistics

*Generated by \`scripts/gen-trace-stats.ts\` from real runs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.*

## Headline

${headline.map((h) => `- ${h}`).join('\n')}

Every one of these instructions can be stepped to, has its full numerical result stored (or recomputable from a checkpoint), and is explained by a generated general formula, a formula with its own numbers substituted, and a plain-language sentence.

## Runnable experiments

${sections.join('\n')}
## Scaling

Instruction count is linear in epochs and in examples per epoch (per-sample execution), grows with depth by a constant number of instructions per layer, and is independent of layer width — width changes the size of each instruction's tensors (trace bytes), not their number. Batch size changes only the per-batch overhead (begin/end, loss reduction and one update block per parameter per batch).

${scaling.join('\n')}`;
writeFileSync(resolve(import.meta.dirname, '../docs/TRACE-STATISTICS.md'), doc);
console.log('wrote docs/TRACE-STATISTICS.md');
