#!/usr/bin/env python3
"""Builds the reduced-MNIST asset bundled with DL-VizLab (P7).

Source: the MNIST database (LeCun, Cortes & Burges), files as mirrored at
https://storage.googleapis.com/cvdf-datasets/mnist/, verified by SHA-256 below.
Licence: MNIST is made available under CC BY-SA 3.0; the subset inherits it.

Selection: digits 0, 1 and 2; 500 training and 100 test images per class drawn
without replacement with numpy.random.default_rng(2026) from the official
training and test splits. Pixels are kept as uint8 (0–255) and scaled to [0, 1]
at load time. Output: src/experiments/data/mnist-subset.ts (base64 strings).

Usage: python3 scripts/gen-mnist-subset.py <dir with the four .gz files>
"""
import base64
import gzip
import hashlib
import sys
from pathlib import Path

import numpy as np

SHA256 = {
    "train-images-idx3-ubyte.gz": "440fcabf73cc546fa21475e81ea370265605f56be210a4024d2ca8f203523609",
    "train-labels-idx1-ubyte.gz": "3552534a0a558bbed6aed32b30c495cca23d567ec52cac8be1a0730e8010255c",
    "t10k-images-idx3-ubyte.gz": "8d422c7b0a1c1c79245a5bcf07fe86e33eeafee792b84584aec276f5a2dbc4e6",
    "t10k-labels-idx1-ubyte.gz": "f7ae60f92e00ec6debd23a6088c31dbd2371eca3ffa0defaefb259924204aec6",
}
CLASSES = [0, 1, 2]
PER_CLASS = {"train": 500, "test": 100}


def read(d: Path, name: str) -> np.ndarray:
    raw = (d / name).read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != SHA256[name]:
        raise SystemExit(f"{name}: checksum {digest} does not match the expected MNIST file")
    data = gzip.decompress(raw)
    offset = 16 if "images" in name else 8
    arr = np.frombuffer(data, dtype=np.uint8, offset=offset)
    return arr.reshape(-1, 28 * 28) if "images" in name else arr


def main() -> None:
    d = Path(sys.argv[1])
    rng = np.random.default_rng(2026)
    out = {}
    for split, prefix in (("train", "train"), ("test", "t10k")):
        images = read(d, f"{prefix}-images-idx3-ubyte.gz")
        labels = read(d, f"{prefix}-labels-idx1-ubyte.gz")
        idx = np.concatenate([rng.choice(np.flatnonzero(labels == c), PER_CLASS[split], replace=False) for c in CLASSES])
        # Interleave classes so any prefix of the data is balanced.
        idx = idx.reshape(len(CLASSES), -1).T.reshape(-1)
        out[split] = (images[idx], np.array([CLASSES.index(c) for c in labels[idx]], dtype=np.uint8))
    b64 = lambda a: base64.b64encode(a.tobytes()).decode()  # noqa: E731
    ts = f"""/* Generated by scripts/gen-mnist-subset.py — do not edit.
 * Reduced MNIST: digits {CLASSES}, {PER_CLASS['train']} train / {PER_CLASS['test']} test per class, 28×28 uint8.
 * Source: MNIST (LeCun, Cortes & Burges), CC BY-SA 3.0. See docs/DATASETS.md. */
export const MNIST_CLASSES = {[str(c) for c in CLASSES]};
export const MNIST_TRAIN_IMAGES = '{b64(out['train'][0])}';
export const MNIST_TRAIN_LABELS = '{b64(out['train'][1])}';
export const MNIST_TEST_IMAGES = '{b64(out['test'][0])}';
export const MNIST_TEST_LABELS = '{b64(out['test'][1])}';
"""
    path = Path(__file__).resolve().parents[1] / "src/experiments/data/mnist-subset.ts"
    path.write_text(ts)
    print(f"wrote {path} ({path.stat().st_size / 1e6:.2f} MB)")


if __name__ == "__main__":
    main()
